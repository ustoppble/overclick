const DICTS: Record<Lang, Dict> = { en, "pt-BR": ptBR };

export function isLang(value: unknown): value is Lang {
  return value === "en" || value === "pt-BR";
}

/** Returns the dictionary for a persisted language value; unknown → English. */
export function dict(lang: string | null | undefined): Dict {
  return isLang(lang) ? DICTS[lang] : en;
}
